DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_producto_stock_no_negativo') THEN
        ALTER TABLE productos ADD CONSTRAINT ck_producto_stock_no_negativo CHECK (stock_actual >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_lote_stock_no_negativo') THEN
        ALTER TABLE lotes ADD CONSTRAINT ck_lote_stock_no_negativo
            CHECK (stock_inicial >= 0 AND stock_actual >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_detalle_compra_cantidad_positiva') THEN
        ALTER TABLE detalle_compras ADD CONSTRAINT ck_detalle_compra_cantidad_positiva
            CHECK (cantidad > 0 AND costo_unitario >= 0 AND subtotal >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_detalle_venta_cantidad_positiva') THEN
        ALTER TABLE detalle_ventas ADD CONSTRAINT ck_detalle_venta_cantidad_positiva
            CHECK (cantidad > 0 AND precio_unitario >= 0 AND subtotal >= 0 AND base_imponible >= 0 AND igv >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_pago_montos_validos') THEN
        ALTER TABLE pagos ADD CONSTRAINT ck_pago_montos_validos
            CHECK (monto > 0 AND monto_recibido >= monto AND vuelto >= 0
                   AND monto_recibido = monto + vuelto);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_venta_montos_validos') THEN
        ALTER TABLE ventas ADD CONSTRAINT ck_venta_montos_validos
            CHECK (subtotal >= 0 AND igv >= 0 AND total >= 0 AND total = subtotal + igv);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_conteo_stock_no_negativo') THEN
        ALTER TABLE inventario_conteo_detalles ADD CONSTRAINT ck_conteo_stock_no_negativo
            CHECK (stock_sistema >= 0 AND stock_contado >= 0 AND diferencia = stock_contado - stock_sistema);
    END IF;
END $$;

